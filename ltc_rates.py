#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
2단계: 장기요양 급여비용(본인부담금) 계산 상수/함수 모음

출처 (2026-11-27, 보건복지부고시 제2025-247호 "장기요양급여 제공기준 및 급여비용 산정방법 등에
관한 고시" 원문 PDF로 직접 교차검증 완료 — 2026년 1월 1일 시행):

- 본인부담률: 재가급여 15%, 시설급여 20%
  - 감경 60%: 시설 8% / 재가 6%
  - 감경 40%: 시설 12% / 재가 9%
  - 의료급여수급권자(국민기초생활보장법): 면제(0%)

- 노인요양시설(A03) 1일 급여비용 — 요양보호사 배치비율에 따라 두 단계 수가가 있음(제44조제1항):
  - 입소자 2.1명당 요양보호사 1명 "이상"(표준): 1등급 93,070 / 2등급 86,340 / 3~5등급 81,540원
    → 이 계산기는 이 표준 수가를 기본값으로 사용함.
  - 입소자 2.1명당 요양보호사 1명 "미만"(배치기준 미달): 1등급 88,520 / 2등급 82,120 / 3~5등급 77,540원
    → API로는 어느 기관이 이 기준에 해당하는지 구분 불가. 계산기 값보다 일 최대 약 4,550원
      (월 약 136,500원) 낮게 나올 수 있다는 점을 UI에 안내해야 함.

- 노인요양공동생활가정(A04) 1일 급여비용(제44조제2항, 배치비율 구분 없음):
  1등급 74,590 / 2등급 69,210 / 3~5등급 63,800원 — 원문 대조 완료.

- 주야간보호(B03) 1일 급여비용(제31조제1항)은 "이용시간대"에 따라 5단계로 나뉨:
  3~6h / 6~8h / 8~10h / 10~13h / 13h 초과. 이 계산기는 그중 "8~10시간" 구간
  (1등급 69,730 / 2등급 64,590 / 3등급 59,640 / 4등급 58,010 / 5등급·인지지원 56,360원)을
  대표값으로 사용함 — 실제 이용시간이 다르면 금액이 달라짐을 UI에 반드시 안내해야 함.
  ※ 주야간보호는 재가급여로 분류되어 본인부담률 15%/감경 6%·9% 체계를 따름(시설급여 20% 체계 아님).

주의:
- 3~5등급은 원칙적으로 시설급여(A03/A04) 입소 대상이 아님(등급판정위원회 심의를 거친 예외적 경우만 가능).
  계산기에서는 "이 등급은 이 시설유형에서 예외 승인 시에만 가능" 안내를 붙여야 함.
- API로는 기관별 요양보호사 배치비율·실제 이용시간대를 구분할 수 없으므로, 이 계산기의 결과는
  "표준 기준 추정치"이며 실제 청구액과 다를 수 있음을 항상 명시해야 함.
"""

# facility_type(adminPttnCd) -> 등급 -> 1일 급여비용(원)
# 3~5등급은 셋 다 동일 금액이라 '3','4','5' 키를 동일값으로 중복 저장
DAILY_RATE = {
    "A03": {  # 노인요양시설
        "1": 93070, "2": 86340, "3": 81540, "4": 81540, "5": 81540,
    },
    "A04": {  # 노인요양공동생활가정
        "1": 74590, "2": 69210, "3": 63800, "4": 63800, "5": 63800,
    },
    "B03": {  # 주야간보호 (8시간 이상 이용 기준, 인지지원등급은 '5'와 동일 취급)
        "1": 69730, "2": 64590, "3": 59640, "4": 58010, "5": 56360, "인지지원": 56360,
    },
}

# facility_type -> '시설' 또는 '재가' (본인부담률 체계 구분용)
BENEFIT_CATEGORY = {
    "A03": "시설",
    "A04": "시설",
    "B03": "재가",
}

# 부담유형 -> (시설 본인부담률, 재가 본인부담률)
COPAY_RATE = {
    "일반": {"시설": 0.20, "재가": 0.15},
    "40%감경": {"시설": 0.12, "재가": 0.09},
    "60%감경": {"시설": 0.08, "재가": 0.06},
    "의료급여수급권자": {"시설": 0.0, "재가": 0.0},
}

CAPACITY_RELEVANT_CODES = {"A03", "A04", "B03"}


def calc_monthly_copay(admin_pttn_cd: str, grade: str, burden_type: str, days: int = 30) -> int:
    """등급·부담유형별 월 급여 본인부담금(원)을 계산한다.

    admin_pttn_cd: 'A03'|'A04'|'B03'
    grade: '1'~'5' 또는 B03의 경우 '인지지원'
    burden_type: '일반'|'40%감경'|'60%감경'|'의료급여수급권자'
    """
    if admin_pttn_cd not in DAILY_RATE:
        raise ValueError(f"지원하지 않는 시설유형: {admin_pttn_cd}")
    if grade not in DAILY_RATE[admin_pttn_cd]:
        raise ValueError(f"{admin_pttn_cd}에서 지원하지 않는 등급: {grade}")
    if burden_type not in COPAY_RATE:
        raise ValueError(f"알 수 없는 부담유형: {burden_type}")

    daily_rate = DAILY_RATE[admin_pttn_cd][grade]
    category = BENEFIT_CATEGORY[admin_pttn_cd]
    rate = COPAY_RATE[burden_type][category]
    daily_copay = round(daily_rate * rate)
    return daily_copay * days


if __name__ == "__main__":
    # 간단 검증: 보도자료에 나온 예시들과 일치하는지 확인
    # 1등급 노인요양시설 일반대상자 30일: 18,614*30 = 558,420 (반올림 차이 있을 수 있음)
    print("A03 1등급 일반 30일:", calc_monthly_copay("A03", "1", "일반", 30))
    print("A03 2등급 40%감경 30일:", calc_monthly_copay("A03", "2", "40%감경", 30))
